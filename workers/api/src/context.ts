import { digest, fail, verifyJwt, type Claims } from './security.js';
import { setupRequestAllowed } from './admin-access.js';

export interface Env extends Partial<ApiBindings> {
  APP_RELEASE?: string;
  SOURCE_SHA?: string;
  EMAIL_DELIVERY_ENABLED?: string;
  DB: ApiBindings['DB']; R2_MEDIA: ApiBindings['R2_MEDIA']; EMAIL_OUTBOX_SECRET?: string;
  JWT_SECRET?: string; ENVIRONMENT?: string; AUTH_CPU_VERIFIED?: string; ENROLLMENT_CPU_VERIFIED?: string;
  ALLOWED_ORIGINS?: string; TRUSTED_SHARED_HOSTS?: string;
  SCHOOL_ACTIVATION_VERIFIED?: string;
  // A narrowly scoped owner-reviewed exception for fully configured tenants.
  // The global flag remains supported for account-wide verification.
  SCHOOL_ACTIVATION_VERIFIED_CODES?: string;
  ADMIN_ACCESS_KEY_SECRET?: string; ADMIN_ACCESS_KEY_CPU_VERIFIED?: string;
  // Platform administrator passwords use the same Free-compatible HMAC password
  // scheme as generated school-user passwords. It intentionally falls back to
  // ADMIN_ACCESS_KEY_SECRET so existing deployments do not need another secret.
  PLATFORM_PASSWORD_SECRET?: string;
  // HMAC-peppered random passwords are only enabled for passwords generated by
  // the administrator. Legacy/imported bcrypt hashes remain behind the
  // measured AUTH_CPU_VERIFIED gate.
  GENERATED_PASSWORD_AUTH_ENABLED?: string;
  SELF_SERVICE_PASSWORD_ENABLED?: string;
  WHATSAPP_GRAPH_API_URL?: string;
  WHATSAPP_PHONE_NUMBER_ID?: string;
  WHATSAPP_PASSWORD_TEMPLATE?: string;
  WHATSAPP_TEMPLATE_LANGUAGE?: string;
  WHATSAPP_ACCESS_TOKEN?: string;
  WHATSAPP_DEFAULT_COUNTRY_CODE?: string;
}
export interface School { id: string; code: string; slug: string; name: string; status: string; timezone: string; currency: string; logo_r2_key: string | null }
export interface User { id: string; school_id: string; user_type: Claims['userType']; full_name: string; email: string | null; mobile: string | null; roles?: string[] }
export type AppEnv = { Bindings: Env; Variables: { school: School; user: User; claims: Claims; tokenDigest: string; requestId: string } };
export type ApiContext = Context<AppEnv>;
export function db(c: ApiContext): D1Database {
  if (!c.env?.DB) fail(503, 'DATABASE_UNAVAILABLE');
  return c.env.DB;
}
export async function schoolByCode(c: ApiContext, code: string): Promise<School> {
  if (!/^[A-Z0-9_-]{2,20}$/.test(code)) fail(400, 'INVALID_SCHOOL_CODE');
  const school = await db(c).prepare('SELECT * FROM schools WHERE code = ?').bind(code).first<School>();
  if (!school) fail(404, 'SCHOOL_NOT_FOUND');
  return school;
}
export async function resolveSchool(c: ApiContext, bodyCode?: string, tokenCode?: string): Promise<School> {
  const host = new URL(c.req.url).hostname.toLowerCase();
  const shared = (c.env?.TRUSTED_SHARED_HOSTS || 'gurukull.in,www.gurukull.in,app.gurukull.in,api.gurukull.in').split(',');
  const local = c.env?.ENVIRONMENT === 'local' && ['localhost','127.0.0.1'].includes(host);
  let mapped: School | null = null;
  if (!shared.includes(host) && !local) {
    if (host.endsWith('.gurukull.in') && host.split('.').length !== 3) fail(404, 'HOST_NOT_FOUND');
    mapped = await db(c).prepare(`SELECT s.* FROM domains d JOIN schools s ON s.id = d.school_id WHERE d.hostname = ? AND d.status = 'active'`).bind(host).first<School>();
    if (!mapped) fail(404, 'HOST_NOT_FOUND');
  }
  const codes = [c.req.header('x-school-code'), bodyCode, tokenCode].filter((v): v is string => !!v).map(v=>v.trim().toUpperCase());
  if (new Set(codes).size > 1 || (mapped && codes.some(code=>code!==mapped!.code))) fail(400, 'TENANT_MISMATCH');
  if (!mapped && !codes.length) fail(400, 'SCHOOL_CODE_REQUIRED');
  const school = mapped || await schoolByCode(c, codes[0]);
  c.set('school', school);
  return school;
}
export const requireAuth: MiddlewareHandler<AppEnv> = async (c,next) => {
  const auth = c.req.header('authorization') || '';
  if (!auth.startsWith('Bearer ')) fail(401, 'UNAUTHORIZED');
  if (!c.env?.JWT_SECRET || new TextEncoder().encode(c.env.JWT_SECRET).length < 32) fail(503, 'AUTH_NOT_CONFIGURED');
  const token = auth.slice(7);
  const claims = await verifyJwt(token, c.env.JWT_SECRET);
  if (!claims) fail(401, 'INVALID_TOKEN');
  const school = await resolveSchool(c, undefined, claims.schoolCode);
  if (school.id !== claims.schoolId) fail(400, 'TENANT_MISMATCH');
  const setup=claims.purpose==='school_setup';
  if (school.status !== 'active' && !(setup&&['configuration_needed','administrator_pending'].includes(school.status))) fail(403, 'SCHOOL_NOT_ACTIVE');
  const tokenDigest = await digest(token);
  const user = await db(c).prepare(`SELECT u.id,u.school_id,u.user_type,u.full_name,u.email,u.mobile,COALESCE((SELECT json_group_array(r.role) FROM user_roles r WHERE r.school_id=u.school_id AND r.user_id=u.id),'[]') AS role_json FROM sessions ss JOIN users u ON u.id=ss.user_id AND u.school_id=ss.school_id WHERE ss.id=? AND ss.school_id=? AND ss.token_digest=? AND ss.revoked_at IS NULL AND ss.expires_at>? AND u.status='active'`).bind(claims.sid, school.id, tokenDigest, Math.floor(Date.now()/1000)).first<User & {role_json:string}>();
  if (!user || user.id !== claims.sub || user.user_type !== claims.userType) fail(401, 'SESSION_REVOKED');
  user.roles = (()=>{try{return JSON.parse(user.role_json || '[]') as string[];}catch{return [] as string[];}})();
  if(setup&&(user.user_type!=='admin'||!setupRequestAllowed(c.req.method,c.req.path)))fail(403,'SCHOOL_SETUP_SCOPE_REQUIRED');
  // Access-key revocation/expiry invalidates existing sessions, not just future login.
  if(claims.authMethod==='admin_access_key'){
   const credential=await db(c).prepare(`SELECT a.id FROM admin_access_credentials a JOIN user_roles r ON r.school_id=a.school_id AND r.user_id=a.user_id AND r.role='admin' WHERE a.id=? AND a.school_id=? AND a.user_id=? AND a.revoked_at IS NULL AND a.expires_at>unixepoch()`).bind(claims.credentialId,school.id,user.id).first();
   if(!credential)fail(401,'SESSION_REVOKED');
  }
  if(claims.authMethod==='member_access_key'){
   const credential=await db(c).prepare(`SELECT a.id FROM user_access_credentials a JOIN user_roles r ON r.school_id=a.school_id AND r.user_id=a.user_id AND r.role=? WHERE a.id=? AND a.school_id=? AND a.user_id=? AND a.revoked_at IS NULL AND a.expires_at>unixepoch()`).bind(user.user_type,claims.credentialId,school.id,user.id).first();
   if(!credential)fail(401,'SESSION_REVOKED');
  }
  c.set('user',user); c.set('claims',claims); c.set('tokenDigest',tokenDigest);
  await next();
};
export function requireRole(c: ApiContext, ...allowed: User['user_type'][]): User {
  const user = c.get('user');
  if (!user || (!allowed.includes(user.user_type) && !allowed.some(role=>user.roles?.includes(role)))) fail(403, 'FORBIDDEN');
  return user;
}
export function activeSchool(c: ApiContext) {
  if (c.get('school').status !== 'active') fail(403, 'SCHOOL_NOT_ACTIVE');
}
export async function child(c: ApiContext, studentId: string) {
  const user = requireRole(c,'parent');
  const row = await db(c).prepare(`SELECT s.* FROM students s JOIN users u ON u.id=s.user_id AND u.school_id=s.school_id JOIN parent_student_links p ON p.school_id=s.school_id AND p.student_id=s.id WHERE s.school_id=? AND p.parent_user_id=? AND (s.id=? OR s.user_id=?) AND s.status='active' AND u.status='active'`).bind(user.school_id,user.id,studentId,studentId).first<Record<string,unknown>>();
  if (!row) fail(404,'STUDENT_NOT_FOUND');
  return row;
}
export async function boundedBytes(c: ApiContext, maximum: number): Promise<Uint8Array> {
  const reader = c.req.raw.body?.getReader();
  if (!reader) return new Uint8Array();
  const parts: Uint8Array[] = []; let size = 0;
  try {
    while (true) { const item = await reader.read(); if (item.done) break; size += item.value.byteLength; if (size > maximum) { await reader.cancel(); fail(413,'BODY_TOO_LARGE'); } parts.push(item.value); }
  } finally { reader.releaseLock(); }
  const bytes = new Uint8Array(size); let offset=0; for (const part of parts) { bytes.set(part,offset);offset+=part.byteLength; } return bytes;
}
export async function readBody(c: ApiContext): Promise<Record<string,unknown>> {
  const type = c.req.header('content-type') || '';
  const text = new TextDecoder().decode(await boundedBytes(c,128*1024));
  try {
    if (type.includes('application/json')) { const body: unknown = JSON.parse(text); if (!body || typeof body !== 'object' || Array.isArray(body)) fail(400,'INVALID_BODY'); return body as Record<string,unknown>; }
    if (type.includes('application/x-www-form-urlencoded')) return Object.fromEntries(new URLSearchParams(text));
  } catch { fail(400,'INVALID_BODY'); }
  fail(415,'UNSUPPORTED_CONTENT_TYPE');
}
